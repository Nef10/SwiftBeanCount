#!/usr/bin/env python3
"""Generate an opt-in app project sharing the normal project's sources and build settings."""
import pathlib
import re
from xml.sax.saxutils import escape

root = pathlib.Path(__file__).resolve().parent.parent
source = root / 'SwiftBeanCountApp.xcodeproj'
destination = root / 'SwiftBeanCountRustLedgerApp.xcodeproj'
marker = destination / '.generated-rustledger-fixture'
if destination.exists() and not marker.exists():
    raise SystemExit(f'Refusing to overwrite an existing project: {destination}')
text = (source / 'project.pbxproj').read_text()
text, count = re.subn(
    r'(isa = XCLocalSwiftPackageReference;\s+relativePath = \.\s*;)',
    r'\1\n\t\t\ttraits = (RustLedger, );', text)
if count != 1:
    raise SystemExit('Expected exactly one local package reference in the normal app project.')
destination.mkdir(exist_ok=True)
(destination / 'project.pbxproj').write_text(text)
for scheme in (source / 'xcshareddata' / 'xcschemes').glob('*.xcscheme'):
    output = destination / 'xcshareddata' / 'xcschemes' / scheme.name
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(scheme.read_text().replace(source.name, destination.name))
marker.write_text('Generated by Scripts/create-rustledger-app-project.py\n')
workspace = root / '.build' / 'rustledger' / 'SwiftBeanCountRustLedger.xcworkspace'
workspace.mkdir(parents=True, exist_ok=True)
(workspace / 'contents.xcworkspacedata').write_text(
    '<?xml version="1.0" encoding="UTF-8"?>\n<Workspace version="1.0">\n'
    f'  <FileRef location="absolute:{escape(str(destination))}"/>\n'
    f'  <FileRef location="absolute:{escape(str(root))}"/>\n'
    '</Workspace>\n')
print(destination)
print(workspace)
