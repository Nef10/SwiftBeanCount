#!/usr/bin/env python3
"""Generate a parser-specific app project without changing the normal project.

Defaults to RustParser for compatibility with existing callers.
"""
import argparse
import pathlib
import re
from xml.sax.saxutils import escape


def generate_project(root: pathlib.Path, parser: str = 'RustParser') -> tuple[pathlib.Path, pathlib.Path]:
    backend = 'RustLedger' if parser == 'RustParser' else 'SwiftParser'
    source = root / 'SwiftBeanCountApp.xcodeproj'
    destination = root / f'SwiftBeanCount{backend}App.xcodeproj'
    marker = destination / f'.generated-{backend.lower()}-fixture'
    if destination.exists() and not marker.exists():
        raise SystemExit(f'Refusing to overwrite an existing project: {destination}')
    text = (source / 'project.pbxproj').read_text()
    traits = 'RustLedger, ' if parser == 'RustParser' else ''
    text, count = re.subn(
        r'(isa = XCLocalSwiftPackageReference;\s+relativePath = \.\s*;)(?:\s+traits\s*=\s*\([^;]*\);)?',
        lambda match: f'{match.group(1)}\n\t\t\ttraits = ({traits});', text)
    if count != 1:
        raise SystemExit('Expected exactly one local package reference in the normal app project.')
    destination.mkdir(exist_ok=True)
    (destination / 'project.pbxproj').write_text(text)
    for scheme in (source / 'xcshareddata' / 'xcschemes').glob('*.xcscheme'):
        output = destination / 'xcshareddata' / 'xcschemes' / scheme.name
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(scheme.read_text().replace(source.name, destination.name))
    marker.write_text('Generated by Scripts/create-rustledger-app-project.py\n')
    workspace = root / '.build' / 'rustledger' / f'SwiftBeanCount{backend}.xcworkspace'
    workspace.mkdir(parents=True, exist_ok=True)
    (workspace / 'contents.xcworkspacedata').write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n<Workspace version="1.0">\n'
        f'  <FileRef location="absolute:{escape(str(destination))}"/>\n'
        f'  <FileRef location="absolute:{escape(str(root))}"/>\n'
        '</Workspace>\n')
    return destination, workspace


if __name__ == '__main__':
    argument_parser = argparse.ArgumentParser(description=__doc__)
    argument_parser.add_argument('--parser', choices=('SwiftParser', 'RustParser'), default='RustParser')
    arguments = argument_parser.parse_args()
    for generated in generate_project(pathlib.Path(__file__).resolve().parent.parent, arguments.parser):
        print(generated)
