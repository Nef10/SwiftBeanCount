#!/usr/bin/env python3
"""Create isolated Xcode package fixtures for complete iOS package testing."""

from __future__ import annotations

import argparse
import pathlib
import re
import shutil
import xml.etree.ElementTree as ET


ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / ".build/rustledger/ios-fixtures"
SCHEME_NAME = "SwiftBeanCountAllTests"
FIXTURE_MARKER = ".swiftbeancount-ios-fixture"
FIXTURE_MARKER_CONTENT = "Generated by Scripts/create-ios-test-fixture.py; safe for regeneration.\n"


def write_scheme(fixture: pathlib.Path, target_names: list[str]) -> None:
    scheme = ET.Element("Scheme", LastUpgradeVersion="2710", version="1.7")
    ET.SubElement(scheme, "BuildAction", parallelizeBuildables="YES", buildImplicitDependencies="YES")
    action = ET.SubElement(
        scheme,
        "TestAction",
        buildConfiguration="Debug",
        selectedDebuggerIdentifier="Xcode.DebuggerFoundation.Debugger.LLDB",
        selectedLauncherIdentifier="Xcode.IDEFoundation.Launcher.PosixSpawn",
        shouldUseLaunchSchemeArgsEnv="YES",
        shouldAutocreateTestPlan="YES",
    )
    testables = ET.SubElement(action, "Testables")
    for name in target_names:
        testable = ET.SubElement(testables, "TestableReference", skipped="NO")
        ET.SubElement(
            testable,
            "BuildableReference",
            BuildableIdentifier="primary",
            BlueprintIdentifier=name,
            BuildableName=name,
            ReferencedContainer="container:",
        )
    path = fixture / ".swiftpm/xcode/xcshareddata/xcschemes" / f"{SCHEME_NAME}.xcscheme"
    path.parent.mkdir(parents=True, exist_ok=True)
    ET.indent(scheme)
    ET.ElementTree(scheme).write(path, encoding="utf-8", xml_declaration=True)


def make_fixture(output: pathlib.Path, name: str, enabled_traits: list[str], targets: list[str]) -> None:
    fixture = output / name
    if fixture.exists() or fixture.is_symlink():
        marker = fixture / FIXTURE_MARKER
        if (
            fixture.is_symlink()
            or not fixture.is_dir()
            or fixture.parent != output
            or not marker.is_file()
            or marker.read_text() != FIXTURE_MARKER_CONTENT
        ):
            raise SystemExit(f"Refusing to replace unexpected fixture path: {fixture}")
        shutil.rmtree(fixture)
    fixture.mkdir(parents=True)
    (fixture / FIXTURE_MARKER).write_text(FIXTURE_MARKER_CONTENT)

    for path in ("Sources", "Tests", "Plugins"):
        shutil.copytree(ROOT / path, fixture / path)
    for path in ("Package.swift", "Package.resolved", ".swiftlint.yml"):
        shutil.copy2(ROOT / path, fixture / path)

    manifest_path = fixture / "Package.swift"
    manifest = manifest_path.read_text()
    trait_declaration = '        .trait(name: "RustLedger", description: "Use rustledger for parsing, interpolation, booking and validation"),\n'
    if manifest.count(trait_declaration) != 1:
        raise SystemExit(f"Could not locate the RustLedger trait declaration in {manifest_path}")
    defaults = ", ".join(f'"{trait}"' for trait in enabled_traits)
    manifest = manifest.replace(
        trait_declaration,
        trait_declaration + f"        .default(enabledTraits: [{defaults}]),\n",
    )
    manifest_path.write_text(manifest)

    workspace = fixture / ".swiftpm/xcode/package.xcworkspace"
    workspace.mkdir(parents=True, exist_ok=True)
    (workspace / "contents.xcworkspacedata").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<Workspace version="1.0"><FileRef location="self:"></FileRef></Workspace>\n'
    )
    write_scheme(fixture, targets)

    selected = ", ".join(enabled_traits) if enabled_traits else "none"
    print(f"{fixture}: {len(targets)} test targets; default traits: {selected}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=pathlib.Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--parser", choices=["SwiftParser", "RustParser"], help="Generate only the selected configuration")
    args = parser.parse_args()

    manifest = (ROOT / "Package.swift").read_text()
    targets = re.findall(r"\.testTarget\(\s*name:\s*\"([^\"]+)\"", manifest)
    if not targets:
        raise SystemExit("No test targets found in Package.swift")
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)

    if args.parser in (None, "SwiftParser"):
        make_fixture(output, "SwiftParser", [], targets)
    if args.parser in (None, "RustParser"):
        make_fixture(output, "RustParser", ["RustLedger"], targets)


if __name__ == "__main__":
    main()
